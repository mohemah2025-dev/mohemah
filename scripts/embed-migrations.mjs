// Embeds migrations/*.sql into the Worker so it can set up a fresh D1 database by itself.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const files = readdirSync("migrations").filter((f) => f.endsWith(".sql")).sort();
const body = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(`migrations/${f}`, "utf8"))} },`).join("\n");
writeFileSync("worker/lib/migrations.gen.ts", `// Generated by scripts/embed-migrations.mjs — do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${body}\n];\n`);
console.log(`embedded ${files.length} migration(s)`);
